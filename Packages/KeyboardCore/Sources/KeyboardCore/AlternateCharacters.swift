/// 길게 누르면 팝업으로 고를 수 있는 대체 문자 매핑. 고칠 곳은 이 표 하나다.
///
/// ⚠️ 아래 목록은 iOS 기본 한국어 키보드를 실기기에서 확인한 값이 아니라 **추측**이다(확인 전).
/// `$` 의 `₩ € £ ¥ ¢` 는 이슈 #22 의 요구(`€` 입력)와 흔히 알려진 통화 키 구성에 맞춘 것이고,
/// 나머지(`-` `"` `.` 등)는 영문 iOS 키보드 관행을 따라 넣었다. 실기기 비교 후 표만 고치면 된다.
/// 팝업의 첫 칸은 늘 원래 문자이고(손가락을 움직이지 않고 떼면 평소처럼 입력), 여기에는 그 뒤 후보만 적는다.
public enum AlternateCharacters {
    public static let table: [Character: [Character]] = [
        "$": ["₩", "€", "£", "¥", "¢"],
        "₩": ["$", "€", "£", "¥", "¢"],
        "£": ["$", "₩", "€", "¥", "¢"],
        "¥": ["$", "₩", "€", "£", "¢"],
        "-": ["–", "—", "•"],
        "\"": ["“", "”", "„", "«", "»"],
        "'": ["‘", "’", "`"],
        ".": ["…"],
        "?": ["¿"],
        "!": ["¡"],
        "%": ["‰"],
        "0": ["°"],
        "&": ["§"],
    ]

    /// `base` 의 대체 문자. 없으면 빈 배열(= 평소처럼 누르는 즉시 입력).
    public static func alternates(for base: Character) -> [Character] {
        table[base] ?? []
    }
}
